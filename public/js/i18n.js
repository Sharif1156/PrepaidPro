const dictionaries = { en, bn };

let currentLang = 'en';

export function setLang(lang) {
  currentLang = dictionaries[lang] ? lang : 'en';
  document.documentElement.lang = currentLang;
  return currentLang;
}

export function getLang() {
  return currentLang;
}

export function t(key, vars = {}, lang = currentLang) {
  const dictionary = dictionaries[lang] || dictionaries.en;
  const template = dictionary[key] ?? dictionaries.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined || vars[name] === null ? match : String(vars[name]),
  );
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    element.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.getAttribute('data-i18n-label')));
  });
}

